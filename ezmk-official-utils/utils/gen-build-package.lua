-- ezmk-official-utils: gen-build-package — build package generator
--
-- Generates a self-contained build package (.tar.gz) from the current project.
-- The package includes all source files, headers, ezmk.toml, and a generated
-- build script so the project can be built on any machine with ezmk installed.
--
-- Usage:
--   ezmk utils gen-build-package [--output <dir>] [--name <name>]

function help()
    return [[
usage: ezmk utils gen-build-package [options]

Generate a self-contained build package (.tar.gz) for the current project.

The package includes:
  - All source files from configured source directories
  - All header files from configured include directories
  - The project ezmk.toml
  - A generated build script (build.sh + build.ps1)

Options:
  -o, --output  <dir>    Output directory (default: current directory)
  -n, --name    <name>   Package name (default: <project_name>-build)
  -h, --help             Show this help

Examples:
  ezmk utils gen-build-package
  ezmk utils gen-build-package -o ../dist -n myapp-v1.0
]]
end

