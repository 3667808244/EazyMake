#!/usr/bin/env python3
"""
embed_skills.py — embed the user-project skills from .claude/skills/ into
src/skill_data.cpp.

Only directories named ezmk-user-* are embedded (1.5.0-dev.8). Each must have
a SKILL.md with YAML frontmatter name/description; the name must match the
directory name. Descriptions are later used by AGENTS.md generation.

Usage:
  python3 scripts/embed_skills.py .claude/skills/ > src/skill_data.cpp
"""

import os
import sys

USER_PREFIX = "ezmk-user-"


def fail(msg: str) -> None:
    print(f"embed_skills: {msg}", file=sys.stderr)
    sys.exit(1)


def parse_frontmatter(path: str, text: str):
    if not text.startswith("---"):
        fail(f"{path}: missing YAML frontmatter")
    end = text.find("\n---", 3)
    if end < 0:
        fail(f"{path}: unterminated YAML frontmatter")
    block = text[3:end]
    name = ""
    description = ""
    for raw in block.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        if key.strip() == "name":
            name = value
        elif key.strip() == "description":
            description = value
    if not name:
        fail(f"{path}: frontmatter missing 'name'")
    if not description:
        fail(f"{path}: frontmatter missing 'description'")
    if "\n" in description or "\r" in description:
        fail(f"{path}: description must be a single line")
    return name, description


def raw_string(value: str, delimiter: str) -> str:
    return f'R"{delimiter}({value}){delimiter}"'


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    if len(sys.argv) < 2:
        print("Usage: python3 embed_skills.py <skills_dir>", file=sys.stderr)
        sys.exit(1)
    root = sys.argv[1]
    if not os.path.isdir(root):
        fail(f"{root} is not a directory")

    skills = []
    for entry in sorted(os.listdir(root)):
        if not entry.startswith(USER_PREFIX):
            continue
        skill_dir = os.path.join(root, entry)
        if not os.path.isdir(skill_dir):
            continue
        path = os.path.join(skill_dir, "SKILL.md")
        if not os.path.isfile(path):
            fail(f"{path}: missing SKILL.md")
        with open(path, "r", encoding="utf-8", newline="") as f:
            content = f.read()
        name, description = parse_frontmatter(path, content)
        if name != entry:
            fail(f"{path}: frontmatter name '{name}' does not match directory '{entry}'")
        if "\r" in content:
            fail(f"{path}: CR byte in SKILL.md (keep it LF-only)")
        skills.append((name, description, content))

    if not skills:
        fail("no ezmk-user-* skills found")

    out = [
        "// Auto-generated by scripts/embed_skills.py — DO NOT EDIT",
        '#include "ezmk/skill_data.hpp"',
        "",
        "namespace ezmk::skills {",
        "",
        "const Skill* all(std::size_t& count) {",
        "    static const Skill k[] = {",
    ]
    for name, description, content in skills:
        delim = "EZSK"
        while f'){delim}"' in content or f'){delim}"' in description or f'){delim}"' in name:
            delim += "_"
        out.append("        {")
        out.append(f"            {raw_string(name, delim)},")
        out.append(f"            {raw_string(description, delim)},")
        out.append(f"            {raw_string(content, delim)},")
        out.append("        },")
    out.extend([
        "    };",
        "    count = sizeof(k) / sizeof(k[0]);",
        "    return k;",
        "}",
        "",
        "} // namespace ezmk::skills",
    ])
    sys.stdout.buffer.write(("\n".join(out) + "\n").encode("utf-8"))


if __name__ == "__main__":
    main()
